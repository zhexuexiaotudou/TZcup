    def test_success_requires_real_returncode_and_nonempty_output(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            contract, preflight, config, identity, calibration, oracle, compiler = self._inputs(root)

            def runner(command, **_kwargs):
                output = root / "working" / "dosod_mlp3x_s_tzcup_rep-int16.hbm"
                output.parent.mkdir(parents=True, exist_ok=True)
                output.write_bytes(b"fixture HBM generated by mocked runner")
                return subprocess.CompletedProcess(command, 0, "compiled", "")

            with mock.patch.object(compile_producer.shutil, "which", return_value=str(compiler)), \
                 mock.patch.object(compile_producer, "validate_preprocessing_oracle", return_value={"canonical": "oracle"}) as validate_oracle:
                receipt = compile_producer.execute_compile(contract_path=contract, preflight_path=preflight, config_path=config,
                                                           identity_path=identity, calibration_manifest_path=calibration,
                                                           preprocessing_oracle_path=oracle, output=root / "evidence", compiler="fake-hb_compile", runner=runner)
            self.assertEqual(receipt["status"], "COMPILED_NOT_BOARD_ACCEPTED")
            self.assertEqual(receipt["returncode"], 0)
            self.assertEqual(receipt["inputs"]["preprocessing_oracle_finalizer"], {
                "path": str(oracle.resolve()), "sha256": _sha(oracle),
            })
            self.assertEqual(validate_oracle.call_count, 2)
            self.assertEqual(receipt["preprocessing_oracle_validation"]["precompile"], receipt["preprocessing_oracle_validation"]["postcompile"])
            self.assertTrue((root / "evidence" / "dosod_hbm_compile_receipt.json").is_file())

