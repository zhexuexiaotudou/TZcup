class MetricRegressionTests(unittest.TestCase):
    def _bindings(self, root: Path, hbm_sha: str, source: str) -> tuple[Path, Path, Path, str, str]:
        holdout = root / "holdout.json"
        adapter = {"status": "VERIFIED", "command": ["official-adapter"]}
